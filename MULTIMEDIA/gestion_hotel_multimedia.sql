-- 1) Table multimédia
CREATE TABLE multimedia (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nom_fichier  VARCHAR2(200) NOT NULL,
    type_media   VARCHAR2(50)  NOT NULL,
    fichier_blob BLOB,
    date_ajout   DATE DEFAULT SYSDATE,
    CONSTRAINT pk_multimedia PRIMARY KEY (id),
    CONSTRAINT chk_type_media CHECK (type_media IN ('image','audio','video','pdf','docx','xlsx'))
);

-- 2) Table de liaison
CREATE TABLE reservation_media (
    id_rm           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    reservation_ref REF hotel_ro.reservation_t SCOPE IS hotel_ro.reservation_ot,
    id_blob         NUMBER NOT NULL,
    date_liaison    DATE DEFAULT SYSDATE,
    CONSTRAINT pk_res_media PRIMARY KEY (id_rm),
    CONSTRAINT fk_rm_blob FOREIGN KEY (id_blob) REFERENCES multimedia(id)
);

